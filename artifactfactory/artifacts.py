            "Describe the problem domain, its history, and why it matters now.\n\n"
            "## Related Work\n\n"
            "- Prior system A — placeholder citation.\n"
            "- Prior system B — placeholder citation.\n"
            "- Prior system C — placeholder citation.\n\n"
