def slugify(text: str, fallback: str = "artifact") -> str:
    text = (text or "").strip().lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    text = text.strip("-")[:60].strip("-")
    return text or fallback


def _one_line(text: str) -> str:
    text = " ".join((text or "").split())
    return text.replace('"', "'")[:200]


class BuildContext:
    def __init__(self, plan, idea, storage, base_key, built, job_id):
        self.plan = plan
        self.idea = idea
        self.storage = storage
        self.base_key = base_key
        self.built = built
        self.job_id = job_id

    def key(self, *parts: str) -> str:
        return "/".join([self.base_key] + [str(p).strip("/") for p in parts])


class ArtifactBuilder:
    type = "base"

    def build(self, ctx: BuildContext, spec: Dict[str, Any]) -> Dict[str, Any]:
        raise NotImplementedError

    def record(self, ctx: BuildContext, spec: Dict[str, Any], key: str,
               files: List[str]) -> Dict[str, Any]:
        artifact = Artifact(
            id=new_id("artifact"),
            plan_id=ctx.plan["id"],
            job_id=ctx.job_id,
            type=self.type,
            name=spec.get("name") or self.type,
            key=key,
            uri=ctx.storage.uri(key),
            files=list(files),
        )
        return artifact.to_dict()

    @staticmethod
    def _w(ctx: BuildContext, key: str, text: str) -> str:
        ctx.storage.put_text(key, text)
        return key


class SourceRepositoryBuilder(ArtifactBuilder):
    type = "source_repository"

    def build(self, ctx, spec):
        params = spec.get("params") or {}
        language = (params.get("language") or "python").lower()
        name = spec.get("name") or slugify(ctx.plan.get("title") or ctx.idea.get("text"))
        base = ctx.key(self.type, name)
        title = ctx.plan.get("title") or name
        summary = ctx.idea.get("text") or title

        # Real content when the idea came from an evaluation run (see evaluation.py); placeholders otherwise.
        rep = evaluation.report_for(ctx) if language == "python" else None
        real = evaluation.source_repo(rep, title, summary) if rep else None
        if real:
            files = [self._w(ctx, f"{base}/README.md", real["readme"])]
            files += [self._w(ctx, f"{base}/{path}", content) for path, content in real["files"].items()]
            return self.record(ctx, spec, base, files)

        files = [self._w(ctx, f"{base}/README.md", self._readme(title, summary, language))]

        if language == "python":
            module = slugify(name).replace("-", "_")
            files.append(self._w(ctx, f"{base}/pyproject.toml", self._pyproject(name, summary)))
            files.append(self._w(ctx, f"{base}/src/{module}/__init__.py",
                                 f'"""Dummy package for {title}."""\n\n__version__ = "0.1.0"\n'))
            files.append(self._w(ctx, f"{base}/src/{module}/main.py", self._main_py(title)))
            files.append(self._w(ctx, f"{base}/tests/test_main.py", self._test_py(module)))
        elif language in ("javascript", "typescript"):
            ext = "ts" if language == "typescript" else "js"
            files.append(self._w(ctx, f"{base}/package.json",
                                 self._package_json(name, summary, language)))
            files.append(self._w(ctx, f"{base}/src/index.{ext}", self._index_js(title)))
            files.append(self._w(ctx, f"{base}/test/index.test.{ext}", self._test_js(name)))
        elif language == "go":
            files.append(self._w(ctx, f"{base}/go.mod", self._go_mod(name)))
            files.append(self._w(ctx, f"{base}/main.go", self._main_go(title)))
        elif language == "rust":
            files.append(self._w(ctx, f"{base}/Cargo.toml", self._cargo_toml(name, summary)))
            files.append(self._w(ctx, f"{base}/src/main.rs", self._main_rs(title)))
        else:
            files.append(self._w(ctx, f"{base}/NOTES.md",
                                 f"# {title}\n\nUnsupported language '{language}' — dummy scaffold only.\n"))

        return self.record(ctx, spec, base, files)

    def _readme(self, title, summary, language):
        return (
            f"# {title}\n\n"
            "> Dummy scaffold generated by Artifact Factory.\n\n"
            f"**Language:** {language}\n\n"
            f"## Summary\n\n{summary}\n\n"
            "## Getting started\n\n"
            "This repository is a placeholder. Replace the dummy source with a real "
            "implementation.\n"
        )

    def _pyproject(self, name, summary):
        return (
            "[build-system]\n"
            'requires = ["setuptools>=61"]\n'
            'build-backend = "setuptools.build_meta"\n\n'
            "[project]\n"
            f'name = "{name}"\n'
            'version = "0.1.0"\n'
            f'description = "{_one_line(summary)}"\n'
            'requires-python = ">=3.9"\n'
        )

    def _main_py(self, title):
        return (
            f'"""Entry point for {title}."""\n\n\n'
            "def main() -> None:\n"
            f'    print("TODO: implement {_one_line(title)}")\n\n\n'
            'if __name__ == "__main__":\n'
            "    main()\n"
        )

    def _test_py(self, module):
        return (
            "import unittest\n\n"
            f"from {module}.main import main\n\n\n"
            "class TestMain(unittest.TestCase):\n"
            "    def test_main_runs(self):\n"
            "        main()\n\n\n"
            'if __name__ == "__main__":\n'
            "    unittest.main()\n"
        )

    def _package_json(self, name, summary, language):
        payload = {
            "name": name,
            "version": "0.1.0",
            "description": _one_line(summary),
            "main": "src/index.ts" if language == "typescript" else "src/index.js",
            "scripts": {"test": 'echo "no tests yet"'},
            "license": "MIT",
        }
        return json.dumps(payload, indent=2) + "\n"

    def _index_js(self, title):
        return (
            f"// Dummy entry point for {title}\n\n"
            "export function main() {\n"
            f'  console.log("TODO: implement {_one_line(title)}");\n'
            "}\n\n"
            "main();\n"
        )

    def _test_js(self, name):
        return (
            f"// Dummy test for {name}\n"
            "export function testPlaceholder() {\n"
            "  return true;\n"
            "}\n"
        )

    def _go_mod(self, name):
        return f"module example.com/{name}\n\ngo 1.21\n"

    def _main_go(self, title):
        return (
            "package main\n\n"
            'import "fmt"\n\n'
            "func main() {\n"
            f'\tfmt.Println("TODO: implement {_one_line(title)}")\n'
            "}\n"
        )

    def _cargo_toml(self, name, summary):
        return (
            "[package]\n"
            f'name = "{name}"\n'
            'version = "0.1.0"\n'
            'edition = "2021"\n'
            f'description = "{_one_line(summary)}"\n\n'
            "[dependencies]\n"
        )

    def _main_rs(self, title):
        return (
            f"// Dummy entry point for {title}\n"
            "fn main() {\n"
            f'    println!("TODO: implement {_one_line(title)}");\n'
            "}\n"
        )


class NpmPackageBuilder(ArtifactBuilder):
    type = "npm_package"

    def build(self, ctx, spec):
        name = spec.get("name") or slugify(ctx.plan.get("title") or ctx.idea.get("text"))
        base = ctx.key(self.type, name)
        title = ctx.plan.get("title") or name
        summary = ctx.idea.get("text") or title
        pkg = {
            "name": name,
            "version": "0.1.0",
            "description": _one_line(summary),
            "main": "index.js",
            "scripts": {"test": 'echo "no tests yet"'},
            "keywords": [],
            "license": "MIT",
        }
        files = [
            self._w(ctx, f"{base}/package.json", json.dumps(pkg, indent=2) + "\n"),
            self._w(ctx, f"{base}/index.js", f"// Dummy NPM package for {title}\nmodule.exports = {{}};\n"),
            self._w(ctx, f"{base}/README.md", f"# {name}\n\nDummy NPM package scaffold.\n\n{summary}\n"),
            self._w(ctx, f"{base}/.npmignore", "test/\n*.log\n"),
        ]
        return self.record(ctx, spec, base, files)


class DockerImageBuilder(ArtifactBuilder):
    type = "docker_image"

    def build(self, ctx, spec):
        name = spec.get("name") or slugify(ctx.plan.get("title") or ctx.idea.get("text"))
        base = ctx.key(self.type, name)
        title = ctx.plan.get("title") or name
        dockerfile = (
            "FROM python:3.11-slim\n\n"
            f'LABEL org.opencontainers.image.title="{name}"\n'
            "WORKDIR /app\n"
            "COPY . /app\n"
            f'CMD ["python", "-c", "print(\'dummy image for {_one_line(title)}\')"]\n'
        )
        manifest = {
            "name": name,
            "tag": "latest",
            "image": f"{name}:latest",
            "created_by": "artifactfactory",
            "dummy": True,
        }
        files = [
            self._w(ctx, f"{base}/Dockerfile", dockerfile),
            self._w(ctx, f"{base}/manifest.json", json.dumps(manifest, indent=2) + "\n"),
        ]
        tar_key = f"{base}/image.tar"
        ctx.storage.put_bytes(tar_key, b"DUMMY DOCKER IMAGE TARBALL\n")
        files.append(tar_key)
        return self.record(ctx, spec, base, files)


class TarballBuilder(ArtifactBuilder):
    type = "tarball"

    def build(self, ctx, spec):
        name = spec.get("name") or slugify(ctx.plan.get("title") or ctx.idea.get("text"))
        base = ctx.key(self.type, name)
        tar_key = f"{base}/{name}.tar.gz"
        buf = io.BytesIO()
        with tarfile.open(fileobj=buf, mode="w:gz") as tar:
            for artifact in ctx.built:
                for fkey in artifact.get("files", []):
                    if not ctx.storage.exists(fkey):
                        continue
                    data = ctx.storage.get_bytes(fkey)
                    arcname = fkey
                    if arcname.startswith(ctx.base_key + "/"):
                        arcname = arcname[len(ctx.base_key) + 1:]
                    info = tarfile.TarInfo(name=arcname)
                    info.size = len(data)
                    info.mtime = 0
                    tar.addfile(info, io.BytesIO(data))
        ctx.storage.put_bytes(tar_key, buf.getvalue())
        return self.record(ctx, spec, tar_key, [tar_key])


class LiteratureReviewBuilder(ArtifactBuilder):
    type = "literature_review"

    def build(self, ctx, spec):
        name = spec.get("name") or slugify(ctx.plan.get("title") or ctx.idea.get("text"))
        base = ctx.key(self.type, name)
        title = ctx.plan.get("title") or name
